// --- LOG.md (generated release journal, derived from CHANGELOG.md) ----------
// Ends the append-drift: the hand-appended journal went unmaintained across
// v5.3.0-v5.17.3 (only STATUS + MANIFEST were gated, never LOG). LOG.md is now a
// pure function of CHANGELOG.md, so check:handoff keeps it in lockstep and it
// cannot silently drift. Decision rationale lives in STATUS.md; the pre-generation
// hand-authored entries are preserved verbatim in LOG-ARCHIVE.md.
// Block-based parse so EVERY release lands in the journal across all historical
// CHANGELOG formats: current "### vX.Y.Z (date)" + "**headline**" line, older
// blocks (v3.0.0-v4.9.0) that jump straight to bullets, and v1/v2 headings with
// no date. Headline = first bold span in the block, else the first bullet/line.
//
// The heading regex is RELEASE_RE, imported from AAHP's changelog-grammar.mjs
// rather than hand-duplicated here. The hand-duplicated version silently
// dropped SemVer pre-release headings ("## [5.26.0-rc.1]") from this table -
// they matched \d+\.\d+\.\d+ nowhere, so the whole release vanished from LOG.md
// with no error. RELEASE_RE's version group additionally accepts an optional
// -[0-9A-Za-z.-]+ suffix, so the fix is a strict superset: identical capture
// for every CHANGELOG heading that already matched, and now matches
// pre-release headings too.
const changelog = rd("CHANGELOG.md");
const clLines = changelog.split("\n");
const heads = [];
clLines.forEach((l, i) => {
  const m = l.match(RELEASE_RE);
  if (m) heads.push({ i, v: m[1], date: m[2] || "" });
});
const releaseRows = heads
  .map(({ i, v, date }, k) => {
    const end = k + 1 < heads.length ? heads[k + 1].i : clLines.length;
    // Headline = first non-empty body line, stripped of a leading bullet and of
    // markdown emphasis/code markers. For current "**headline**" blocks this is
    // the headline; for older bullet-first blocks it is the first bullet's text.
    let headline = (clLines.slice(i + 1, end).find(
      (l) => l.trim() && !/^###\s/.test(l.trim()),
    ) || "")
      .replace(/\*\*/g, "") // strip bold markers FIRST so a "**headline**" prefix
      .replace(/^[-*]\s*/, "") // isn't mistaken for a leading bullet by this strip
      .replace(/`/g, "");
    // Collapse whitespace, drop any non-ASCII mojibake, escape table pipes, cap length.
    headline = headline.replace(/\s+/g, " ").replace(/[^\x20-\x7E]/g, "").replace(/\|/g, "\\|").trim();
    if (headline.length > 120) headline = headline.slice(0, 117).trimEnd() + "...";
    return `| v${v} | ${date || "-"} | ${headline} |`;
  })
  .join("\n");
const releaseCount = heads.length;

const log = `# supply-chain-guard: Release Journal

> AUTO-GENERATED by scripts/scg-handoff-docs.mjs from CHANGELOG.md. Do NOT hand-edit.
> Run \`npm run handoff:refresh\` to update. \`npm run check:handoff\` (in prebuild)
> fails the build if this file is stale, so it cannot silently drift - the append
> gap across v5.3.0-v5.17.3 is exactly why it is generated now, not hand-appended.
> Decision rationale + in-progress notes live in STATUS.md; full release notes in
> CHANGELOG.md; pre-generation hand-authored entries in LOG-ARCHIVE.md.

---

This generated journal lists every release derived from CHANGELOG.md, newest first.

## Releases (${releaseCount}, newest first)

| Version | Date | Headline |
|---------|------|----------|
${releaseRows}
`;

// --- write or check ---------------------------------------------------------

const targets = [
  ["DASHBOARD.md", dashboard],
  ["TRUST.md", trust],
  ["LOG.md", log],
];
const norm = (s) => s.replace(/\r/g, ""); // CRLF-agnostic (Windows working tree)

/**
 * Blank the version column of the Toolchain table for COMPARISON purposes only.
 *
 * That table lists every dependency and its range straight out of package.json,
 * so ANY bump - runtime or dev - made DASHBOARD.md stale and turned the build
 * red on prebuild. Dependabot cannot run `handoff:refresh` (its PRs get a
 * read-only token), so every single dependency PR arrived red and needed a human
 * to hand-pull the bump into a release commit. That is friction with no safety
 * behind it: the table is derived entirely from a file in the SAME commit, so it
 * can always be regenerated and can never encode a stale claim about anything
 * that is not already visible in package.json.
 *
 * The real versions are still written on every `handoff:refresh`; they are only
 * excluded from the staleness check. Everything else in the file - version,
 * module count, test-file count, tsconfig types, release table - stays gated.
 */
const ungateToolchainVersions = (s) =>
  s.replace(/## Toolchain\n[\s\S]*?(?=\nOverrides:)/, (block) =>
    block.replace(/^\| (.+?) \| .*? \|$/gm, "| $1 | - |"),
  );

const cmp = (s) => ungateToolchainVersions(norm(s));

// MANIFEST.json stores a sha256 checksum per handoff file; "AAHP Verify"
// Layer 1 (lint-handoff.sh) fails if any stored checksum does not match the
// file on disk. Regenerating DASHBOARD.md/TRUST.md here (e.g. on a version
// bump) changes those files, so the manifest MUST be regenerated in the same
// step or CI goes red on the next push - the recurring on-deploy failure. We
// keep both in lockstep on write, and gate on it in --check (CI parity,
// offline). See @elvatis_com/aahp/scripts/_aahp-lib.sh -> aahp_checksum() for
// the hash contract.
const manifestPath = join(handoff, "MANIFEST.json");
// Mirror aahp_checksum() EXACTLY: strip CR, sha256 the bytes, prefix "sha256:".
const diskChecksum = (name) => {
  const lf = readFileSync(join(handoff, name)).toString("latin1").replace(/\r/g, "");
  return "sha256:" + createHash("sha256").update(Buffer.from(lf, "latin1")).digest("hex");
};
const staleManifestFiles = () => {
  if (!existsSync(manifestPath)) return [];
  const m = JSON.parse(readFileSync(manifestPath, "utf8"));
  return Object.keys(m.files || {}).filter(
    (name) =>
      existsSync(join(handoff, name)) &&
      m.files[name].checksum !== diskChecksum(name),
  );
};

if (process.argv.includes("--check")) {
  const stale = targets.filter(([name, content]) => {
    const p = join(handoff, name);
    const current = existsSync(p) ? readFileSync(p, "utf8") : "";
    return cmp(current) !== cmp(content);
  });
  if (stale.length > 0) {
    console.error(
      `\n  Handoff docs are stale: ${stale.map(([n]) => n).join(", ")}.\n` +
        `  These are generated from package.json + tsconfig + the src/ file list.\n` +
        `  Fix: run \`npm run handoff:refresh\`, then re-commit.\n`,
    );
    process.exit(1);
  }
  const staleManifest = staleManifestFiles();
  if (staleManifest.length > 0) {
    console.error(
      `\n  MANIFEST.json checksums are stale: ${staleManifest.join(", ")}.\n` +
        `  The handoff docs are current but the checksum manifest was not\n` +
        `  regenerated - this is the exact cause of "AAHP Verify" Layer 1\n` +
        `  failing in CI after a version bump / release.\n` +
        `  Fix: run \`npm run handoff:refresh\`, then re-commit.\n`,
    );
    process.exit(1);
  }
  // Freshness gate for the hand-maintained backlog doc: its stated current
  // version must equal package.json. This is the ungated hand-doc drift that let
  // NEXT_ACTIONS.md sit on "v5.6.0" while the repo shipped v5.17.3. Only the
  // designated header line is checked (not the historical "Recently Completed"
  // versions, which are legitimately older).
  const naPath = join(handoff, "NEXT_ACTIONS.md");
  if (existsSync(naPath)) {
    const m = readFileSync(naPath, "utf8").match(/Current version:\s*\*\*v(\d+\.\d+\.\d+)\*\*/i);
    if (m && m[1] !== pkg.version) {
      console.error(
        `\n  NEXT_ACTIONS.md "Current version" is v${m[1]} but package.json is v${pkg.version}.\n` +
          `  The hand-curated backlog fell behind the release - the exact ungated drift\n` +
          `  this gate now catches. Update its header to v${pkg.version}, then re-commit.\n`,
      );
      process.exit(1);
    }
  }
  console.log(
    "Handoff docs up to date: DASHBOARD.md, TRUST.md, LOG.md; MANIFEST.json in sync; " +
      "NEXT_ACTIONS.md current-version header matches package.json.",
  );
} else {
  for (const [name, content] of targets) writeFileSync(join(handoff, name), content);
  // Regenerate MANIFEST.json so its checksums match the docs we just wrote.
  // Delegate to the PACKAGED canonical writer (keeps token budget / context /
  // last session authoritative and re-checksums every tracked file, not only
  // these two), resolved via node_modules rather than a vendored local copy so
  // this repo cannot drift from AAHP's own manifest generator again. Interpreter
  // resolution (resolveBash) and Windows path conversion (toBashPath) are
  // imported from @elvatis_com/aahp/scripts/aahp-config.mjs above rather than
  // duplicated - see that module for why plain "bash" on Windows PATH is
  // unsafe (resolves to the WSL launcher, which has no C: drive) and why a
  // native backslash path breaks (Git-Bash/MSYS consumes each backslash as an
  // escape). AAHP_BASH still overrides the interpreter search.
  const manifestScript = require.resolve("@elvatis_com/aahp/scripts/aahp-manifest.sh");
  try {
    execFileSync(
      resolveBash(),
      [
        toBashPath(manifestScript, process.platform, repoRoot),
        toBashPath(repoRoot, process.platform, repoRoot),
        "--agent",
        "handoff-refresh",
        "--phase",
        "idle",
        "--quiet",
      ],
      { stdio: "inherit", cwd: repoRoot },
    );
  } catch (err) {
    console.error(
      `\n  DASHBOARD.md + TRUST.md were written, but MANIFEST.json regen failed:\n` +
        `  ${err.message}\n` +
        `  Run manually: npx aahp manifest . --quiet\n`,
    );
    process.exit(1);
  }
  console.log(
    `handoff:refresh OK - DASHBOARD.md + TRUST.md + LOG.md + MANIFEST.json regenerated ` +
      `(modules=${modules.length}, testFiles=${testFiles.length}, releases=${releaseCount}, ` +
      `types:[node]=${typesNode}).`,
  );
}
