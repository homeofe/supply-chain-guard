#!/usr/bin/env node
// Renders the README ecosystem-coverage table from src/ecosystem-coverage.json
// (the claim, proven row by row in src/__tests__/coverage-matrix.test.ts) and
// the indicator data actually shipped (feed.json + data/threat-catalog.jsonl).
//
//   node scripts/generate-coverage-table.mjs          -> rewrite the README block
//   node scripts/generate-coverage-table.mjs --check  -> FAIL if the README block differs
//
// The data column states only WHETHER indicators exist, not how many: counts
// change with every daily import and would make this gate noise. It flips when
// an ecosystem gets its first indicator, which is exactly the claim change a
// reviewer should see. Runs after check:feed, so feed.json is current.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const BEGIN = "<!-- ecosystem-coverage:begin (generated by scripts/generate-coverage-table.mjs; edit src/ecosystem-coverage.json) -->";
const END = "<!-- ecosystem-coverage:end -->";

export function countByPrefix(values, prefixes) {
  let n = 0;
  for (const v of values) {
    for (const p of prefixes) {
      if (p === "" ? !v.includes(":") : v.startsWith(`${p}:`)) { n++; break; }
    }
  }
  return n;
}

export function renderTable(coverage, bundleValues, catalogValues) {
  const rows = [
    "| Ecosystem | Files read | Rule | Indicators shipped | Imported automatically from |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const e of coverage.ecosystems) {
    const bundled = countByPrefix(bundleValues, e.prefixes);
    const catalog = countByPrefix(catalogValues, e.prefixes);
    const data = bundled && catalog ? "bundle + catalog"
      : bundled ? "bundle"
        : catalog ? "catalog"
          : "none yet (matcher ready)";
    const files = e.formats.map((f) => `\`${f}\``).join(", ");
    const rules = e.rules.map((r) => `\`${r}\``).join(", ");
    rows.push(`| ${e.label} | ${files} | ${rules} | ${data} | ${e.import} |`);
  }
  return rows.join("\n");
}

function load() {
  const coverage = JSON.parse(readFileSync(join(root, "src", "ecosystem-coverage.json"), "utf8"));
  const feed = JSON.parse(readFileSync(join(root, "feed.json"), "utf8"));
  const bundleValues = feed.entries.filter((e) => e.type === "package").map((e) => e.value);
  const catalogValues = readFileSync(join(root, "data", "threat-catalog.jsonl"), "utf8")
    .split("\n").filter(Boolean).map((l) => JSON.parse(l)).filter((e) => e.type === "package").map((e) => e.value);
  return { coverage, bundleValues, catalogValues };
}

function main() {
  const check = process.argv.includes("--check");
  const { coverage, bundleValues, catalogValues } = load();
  const table = renderTable(coverage, bundleValues, catalogValues);
  const readmePath = join(root, "README.md");
  const readme = readFileSync(readmePath, "utf8");
  const nl = readme.includes("\r\n") ? "\r\n" : "\n";
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) {
    console.error(`check:coverage FAILED - README.md has no "${BEGIN}" ... "${END}" block.`);
    process.exit(1);
  }
  const block = `${BEGIN}${nl}${table.replace(/\n/g, nl)}${nl}${END}`;
  const current = readme.slice(start, end + END.length);
  if (check) {
    if (current !== block) {
      console.error("check:coverage FAILED - the README ecosystem table does not match src/ecosystem-coverage.json and the shipped indicator data.");
      console.error("  Fix: npm run coverage:generate, then commit README.md.");
      process.exit(1);
    }
    console.log(`coverage table up to date (${coverage.ecosystems.length} ecosystems).`);
    return;
  }
  writeFileSync(readmePath, readme.slice(0, start) + block + readme.slice(end + END.length));
  console.log(`coverage:generate OK - README ecosystem table written (${coverage.ecosystems.length} ecosystems).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
