#!/usr/bin/env node
// Renders the two generated README blocks from src/ecosystem-coverage.json
// (the claim, proven row by row in src/__tests__/coverage-matrix.test.ts) and
// the indicator data actually shipped (feed.json + data/threat-catalog.jsonl):
//   - ecosystem-list:     which ecosystems ship indicators and which have a
//                         tested matcher but no known malicious package yet;
//   - ecosystem-coverage: the per-ecosystem table.
//
//   node scripts/generate-coverage-table.mjs          -> rewrite both README blocks
//   node scripts/generate-coverage-table.mjs --check  -> FAIL if either block differs
//
// The data column states only WHETHER indicators exist, not how many: counts
// change with every daily import and would make this gate noise. It flips when
// an ecosystem gets its first indicator, which is exactly the claim change a
// reviewer should see; the advertised "N ecosystems" (aahp.config.json claims,
// floor scripts/count-ecosystems.mjs) then has to be raised too. Runs after
// check:feed, so feed.json is current.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const TABLE = {
  begin: "<!-- ecosystem-coverage:begin (generated by scripts/generate-coverage-table.mjs; edit src/ecosystem-coverage.json) -->",
  end: "<!-- ecosystem-coverage:end -->",
};
const LIST = {
  begin: "<!-- ecosystem-list:begin (generated by scripts/generate-coverage-table.mjs; edit src/ecosystem-coverage.json) -->",
  end: "<!-- ecosystem-list:end -->",
};

export function countByPrefix(values, prefixes) {
  let n = 0;
  for (const v of values) {
    for (const p of prefixes) {
      if (p === "" ? !v.includes(":") : v.startsWith(`${p}:`)) { n++; break; }
    }
  }
  return n;
}

/**
 * Split the declared ecosystems: indicators ship and can match (`withData`,
 * the only ones counted as covered), indicators ship but can only match a
 * legacy format no current tool writes (`limited`, declared by a `limitation`
 * in src/ecosystem-coverage.json), and no indicator yet (`without`).
 */
export function ecosystemsWithData(coverage, bundleValues, catalogValues) {
  const withData = [];
  const limited = [];
  const without = [];
  for (const e of coverage.ecosystems) {
    const bundled = countByPrefix(bundleValues, e.prefixes);
    const catalog = countByPrefix(catalogValues, e.prefixes);
    const row = { ...e, bundled, catalog };
    if (!bundled && !catalog) without.push(row);
    else if (e.limitation) limited.push(row);
    else withData.push(row);
  }
  return { withData, limited, without };
}

export function renderTable(coverage, bundleValues, catalogValues) {
  const rows = [
    "| Ecosystem | Files read | Rule | Indicators shipped | Imported automatically from |",
    "| --- | --- | --- | --- | --- |",
  ];
  const { withData, limited, without } = ecosystemsWithData(coverage, bundleValues, catalogValues);
  const byId = new Map([...withData, ...limited, ...without].map((e) => [e.id, e]));
  for (const declared of coverage.ecosystems) {
    const e = byId.get(declared.id);
    const shipped = e.bundled && e.catalog ? "bundle + catalog"
      : e.bundled ? "bundle"
        : e.catalog ? "catalog"
          : "none yet (matcher ready)";
    const data = e.limitation && (e.bundled || e.catalog) ? `${shipped} (legacy format only)` : shipped;
    const files = e.formats.map((f) => `\`${f}\``).join(", ");
    const rules = e.rules.map((r) => `\`${r}\``).join(", ");
    rows.push(`| ${e.label} | ${files} | ${rules} | ${data} | ${e.import} |`);
  }
  return rows.join("\n");
}

const joinList = (items) =>
  items.length <= 1 ? items.join("") : `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}`;

/**
 * The sentence every other surface's number is checked against. The count of
 * matcher-only ecosystems is deliberately written without the word
 * "ecosystems", so the claims gate reads exactly one number here.
 */
export function renderList(coverage, bundleValues, catalogValues) {
  const { withData, limited, without } = ecosystemsWithData(coverage, bundleValues, catalogValues);
  const lines = [
    `- Known-malicious indicators ship for ${withData.length} ecosystems: ${joinList(withData.map((e) => e.label))}.`,
  ];
  for (const e of limited) {
    lines.push(`- ${e.label} has a tested matcher and ships an indicator, but is not counted: ${e.limitation}.`);
  }
  if (without.length) {
    lines.push(
      `- Matchers are built and tested, but no malicious package is publicly known yet, for ${without.length} more: ${joinList(without.map((e) => e.label))}. ` +
        "They report the day an indicator is published, through the importer or a curated entry.",
    );
  }
  return lines.join("\n");
}

export function load() {
  const coverage = JSON.parse(readFileSync(join(root, "src", "ecosystem-coverage.json"), "utf8"));
  const feed = JSON.parse(readFileSync(join(root, "feed.json"), "utf8"));
  const bundleValues = feed.entries.filter((e) => e.type === "package").map((e) => e.value);
  const catalogValues = readFileSync(join(root, "data", "threat-catalog.jsonl"), "utf8")
    .split("\n").filter(Boolean).map((l) => JSON.parse(l)).filter((e) => e.type === "package").map((e) => e.value);
  return { coverage, bundleValues, catalogValues };
}

function replaceBlock(readme, markers, body, nl) {
  const start = readme.indexOf(markers.begin);
  const end = readme.indexOf(markers.end);
  if (start < 0 || end < start) {
    console.error(`check:coverage FAILED - README.md has no "${markers.begin}" ... "${markers.end}" block.`);
    process.exit(1);
  }
  const block = `${markers.begin}${nl}${body.replace(/\n/g, nl)}${nl}${markers.end}`;
  return {
    current: readme.slice(start, end + markers.end.length),
    block,
    next: readme.slice(0, start) + block + readme.slice(end + markers.end.length),
  };
}

function main() {
  const check = process.argv.includes("--check");
  const { coverage, bundleValues, catalogValues } = load();
  const readmePath = join(root, "README.md");
  let readme = readFileSync(readmePath, "utf8");
  const nl = readme.includes("\r\n") ? "\r\n" : "\n";
  const { withData } = ecosystemsWithData(coverage, bundleValues, catalogValues);
  const summary = `${withData.length} of ${coverage.ecosystems.length} ecosystems ship indicators`;
  let drift = false;
  for (const [markers, body] of [
    [LIST, renderList(coverage, bundleValues, catalogValues)],
    [TABLE, renderTable(coverage, bundleValues, catalogValues)],
  ]) {
    const r = replaceBlock(readme, markers, body, nl);
    if (r.current !== r.block) drift = true;
    readme = r.next;
  }
  if (check) {
    if (drift) {
      console.error("check:coverage FAILED - a generated README ecosystem block does not match src/ecosystem-coverage.json and the shipped indicator data.");
      console.error("  Fix: npm run coverage:generate, then commit README.md (and raise the 'ecosystem count' claim if the number changed).");
      process.exit(1);
    }
    console.log(`coverage blocks up to date (${summary}).`);
    return;
  }
  writeFileSync(readmePath, readme);
  console.log(`coverage:generate OK - README ecosystem blocks written (${summary}).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
